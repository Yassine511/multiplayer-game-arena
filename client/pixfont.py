_FALLBACK = "?"
_ALIASES = {"–": "-", "—": "-", "’": "'", "‘": "'", "“": '"', "”": '"',
            "·": "-", "•": "-", " ": " "}

# glyph -> (width, [(x, y), ...])
_DOTS = {}
for _ch, _rows in _G.items():
    _w = max(len(r) for r in _rows)
    _DOTS[_ch] = (_w, [(x, y) for y, r in enumerate(_rows) for x, c in enumerate(r) if c == "#"])


def _glyph(ch):
    ch = _ALIASES.get(ch, ch)
    g = _DOTS.get(ch)
    if g is None:
        import unicodedata                       # é -> e, ç -> c ...
        base = unicodedata.normalize("NFKD", ch)[:1]
        g = _DOTS.get(base) or _DOTS[_FALLBACK]
    return g


def scale_for(size):
    """Whole-number dot size for a nominal font size (cap height is about 0.7 x size)."""
    return max(2, round(size / 10))


def line_width(s, bold=False):
    """Width in dots, including the one-dot shadow column."""
    if not s:
        return 1
    return sum(_glyph(c)[0] for c in s) + SPACING * (len(s) - 1) + 1


def width(s, size, bold=False):
    return line_width(str(s), bold) * scale_for(size)


def height(size):
    return (TOP_PAD + ROWS + 1) * scale_for(size)


def render(s, size, color, bold=False, shadow=True, shadow_color=(8, 10, 30)):
    """The string as a hard-edged surface (per-pixel alpha)."""
    s = str(s)
    k = scale_for(size)
    w, h = line_width(s, bold), TOP_PAD + ROWS + 1
    small = pygame.Surface((w, h), pygame.SRCALPHA)
    layers = ([((0, 1), shadow_color), ((1, 1), shadow_color)] if shadow else []) + [((0, 0), color)]
    for (ox, oy), col in layers:
        x = 0
        for ch in s:
            gw, dots = _glyph(ch)
            for dx, dy in dots:
                small.set_at((x + dx + ox, TOP_PAD + dy + oy), col)
            x += gw + SPACING
    return pygame.transform.scale(small, (w * k, h * k))
